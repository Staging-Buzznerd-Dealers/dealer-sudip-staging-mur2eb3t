/** Every part name any behaviour recognises. */
export const PARTS = [
  ...new Set(Object.values(BEHAVIOUR_PARTS).flatMap(parts => Object.keys(parts))),
  // Generated by the carousel and rotator inside their dots container, and listed
  // so hand-authored dots validate too.
  'dot',
].sort();

